// Generate src/wudict.schema.d.ts from wuDict's openapi.yaml at the pinned tag (../../WUDICT_VERSION).
// PXDict's own /app-api contract is the zod schemas in src/api/, so it needs no generation.
//
//   npm run gen:api               write the file
//   npm run gen:api -- --check    fail if the committed file is out of date (CI)
//
// Environment: WUDICT_VERSION overrides ../../WUDICT_VERSION; WUDICT_REPO (default wuweidict/wudict);
// WUDICT_OPENAPI=<path> uses a local spec instead of downloading it.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const check = process.argv.includes("--check");

const version =
  process.env.WUDICT_VERSION?.trim() || (await readFile(here("../WUDICT_VERSION"), "utf8")).trim();
const repo = process.env.WUDICT_REPO?.trim() || "wuweidict/wudict";
const out = "src/wudict.schema.d.ts";

async function wudictSpec() {
  if (process.env.WUDICT_OPENAPI) return readFile(process.env.WUDICT_OPENAPI, "utf8");
  const url = `https://raw.githubusercontent.com/${repo}/${version}/internal/server/web/openapi.yaml`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url}: HTTP ${res.status}`);
  const text = await res.text();
  // Keep a local copy (git-ignored) for reference and offline re-runs.
  await mkdir(here("../.cache"), { recursive: true });
  await writeFile(here(`../.cache/wudict-openapi-${version}.yaml`), text);
  return text;
}

const ast = await openapiTS(await wudictSpec());
const body =
  `// Generated by \`npm run gen:api\` from ${repo}@${version} internal/server/web/openapi.yaml. Do not edit by hand.\n\n` +
  astToString(ast);

if (check) {
  const current = await readFile(here(out), "utf8").catch(() => "");
  if (current !== body) {
    console.error(`shared/${out} is out of date: run \`npm run gen:api\` and commit the result.`);
    process.exit(1);
  }
} else {
  await writeFile(here(out), body);
  console.log(`wrote shared/${out}`);
}
