// Generate TypeScript types for both backends:
//   src/api/wudict.schema.d.ts  from wuDict's openapi.yaml at the pinned tag (../WUDICT_VERSION)
//   src/api/app.schema.d.ts     from ../gateway/openapi.yaml
//
//   npm run gen:api               write the files
//   npm run gen:api -- --check    fail if the committed files are out of date (CI)
//
// Environment: WUDICT_VERSION overrides ../WUDICT_VERSION; WUDICT_REPO (default wuweidict/wudict);
// WUDICT_OPENAPI=<path> uses a local spec instead of downloading it.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const check = process.argv.includes("--check");

const version =
  process.env.WUDICT_VERSION?.trim() || (await readFile(root("../WUDICT_VERSION"), "utf8")).trim();
const repo = process.env.WUDICT_REPO?.trim() || "wuweidict/wudict";

async function wudictSpec() {
  if (process.env.WUDICT_OPENAPI) return readFile(process.env.WUDICT_OPENAPI, "utf8");
  const url = `https://raw.githubusercontent.com/${repo}/${version}/internal/server/web/openapi.yaml`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url}: HTTP ${res.status}`);
  const text = await res.text();
  // Keep a local copy (git-ignored) for reference and offline re-runs.
  await writeFile(root("openapi.yaml"), text);
  return text;
}

const targets = [
  {
    out: "src/api/wudict.schema.d.ts",
    source: `${repo}@${version} internal/server/web/openapi.yaml`,
    spec: await wudictSpec(),
  },
  {
    out: "src/api/app.schema.d.ts",
    source: "gateway/openapi.yaml",
    spec: await readFile(root("../gateway/openapi.yaml"), "utf8"),
  },
];

let stale = false;
for (const t of targets) {
  const ast = await openapiTS(t.spec);
  const body =
    `// Generated by \`npm run gen:api\` from ${t.source}. Do not edit by hand.\n\n` +
    astToString(ast);
  const path = root(t.out);
  if (check) {
    const current = await readFile(path, "utf8").catch(() => "");
    if (current !== body) {
      console.error(`${t.out} is out of date: run \`npm run gen:api\` and commit the result.`);
      stale = true;
    }
  } else {
    await writeFile(path, body);
    console.log(`wrote ${t.out}`);
  }
}
if (stale) process.exit(1);
