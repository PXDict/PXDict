// Regenerates src/db/auth-schema.ts (Better Auth's tables as a Drizzle schema) with the Better Auth CLI
// at the same version as the better-auth dependency. Run after upgrading Better Auth or changing the
// plugin list, then `npm run db:generate` for the migration. `--check` fails if the file is stale.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const target = path.join(root, "src/db/auth-schema.ts");
const check = process.argv.includes("--check");
const { version } = JSON.parse(readFileSync(path.join(root, "../node_modules/better-auth/package.json"), "utf8"));

const header = `// GENERATED by \`npm run auth:schema -w @pxdict/gateway\` (Better Auth CLI ${version}); do not edit.
// Better Auth's tables (docs/PLAN.md §1). Inputs: scripts/auth-schema.config.ts.
`;

const dir = mkdtempSync(path.join(tmpdir(), "pxdict-auth-schema-"));
try {
  const out = path.join(dir, "auth-schema.ts");
  execFileSync(
    "npx",
    ["-y", `auth@${version}`, "generate", "--config", "scripts/auth-schema.config.ts", "--output", out,
      "--adapter", "drizzle", "--dialect", "sqlite", "--yes"],
    { cwd: root, stdio: ["ignore", "ignore", "inherit"] },
  );
  const generated = header + readFileSync(out, "utf8");
  if (check) {
    if (readFileSync(target, "utf8") !== generated) {
      console.error("src/db/auth-schema.ts is out of date; run `npm run auth:schema -w @pxdict/gateway`");
      process.exit(1);
    }
  } else {
    writeFileSync(target, generated);
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
